# Writes one script per track, tutorial_insects.R and tutorial_plankton.R, from the R
# code blocks of the tutorial, so that the scripts and the tutorial cannot drift
# apart. Run from the root of the repo after any change to the tutorial.

code_blocks <- function(path) {
  lines <- readLines(path, encoding = "UTF-8", warn = FALSE)
  opens <- which(lines == "```r")
  closes <- which(lines == "```")
  unlist(lapply(opens, function(start) {
    end <- closes[closes > start][1]
    c(lines[(start + 1):(end - 1)], "")
  }))
}

libraries <- c(
  "library(asvoccur)",
  "library(duckplyr)",
  "library(ecolongr)",
  "library(vegan)",
  "library(rworldmap)",
  "library(lubridate)",
  "library(ggplot2)"
)

for (track in c("insects", "plankton")) {
  steps <- c(
    "tutorial-02-prep.qmd",
    sprintf("%s-%02d-%s.qmd", track, 3:6, c("map", "beta", "alpha", "composition"))
  )
  header <- c(
    sprintf("# Step-by-step tutorial code for the %s track, to paste into RStudio on the workshop VM.", track),
    "# Generated by build_tutorial_scripts.R from the tutorial .qmd files. Do not edit by hand.",
    "",
    libraries,
    "",
    sprintf('data_path  <- "/srv/course-data/%s"', track),
    sprintf('store_path <- "/srv/course-store/%s"', track),
    ""
  )
  body <- unlist(lapply(steps, function(step) {
    c(paste("# ---", step, "---"), "", code_blocks(step))
  }))
  writeLines(c(header, body), sprintf("tutorial_%s.R", track), useBytes = TRUE)
}
